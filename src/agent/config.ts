import { EXERCISES } from '../engine/exercises';
import { agentSystemPrompt } from './prompt';
import { AGENT_TOOLS } from './tools';

/**
 * The agent function's instructions and tools, as a file for supabase/functions/agente:
 * fixed on the server, so nobody can use the key for anything else. Written by
 * scripts/agente-config.ts; a test fails when the file and src/agent part ways. The
 * catalog ids, an enum in four tools, are written once.
 */
export function agentConfigSource(): string {
  const ids = JSON.stringify(EXERCISES.map((e) => e.id));
  const tools = JSON.stringify(AGENT_TOOLS).split(ids).join('IDS');
  return [
    '// Generated by scripts/agente-config.ts from src/agent: do not edit by hand.',
    `const IDS = ${ids};`,
    `export const SYSTEM = ${JSON.stringify(agentSystemPrompt())};`,
    `export const TOOLS = ${tools};`,
    '',
  ].join('\n');
}

export const AGENT_CONFIG_PATH = 'supabase/functions/agente/config.ts';
