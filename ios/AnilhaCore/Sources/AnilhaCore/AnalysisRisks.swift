import Foundation

public extension WorkoutAnalysis {
    /// Same frequency, taxonomy and weeklyCap as the TS weeklyVolume/weekRisks projection.
    static func reviewMetrics(_ b: ReadRow) -> ReadRow {
        let p = b.object("params"), plan = b.object("plan")
        var values: [String: Double] = [:]
        for routine in b.array("routines") where !routine.deleted && routine.bool("archived") != true {
            let origin = routine.string("origin")
            let reason = routine.string("reason") ?? ""
            let isPlan = origin.map { $0 == "plano" } ?? (!routine.id.hasPrefix("pronta-") && !routine.id.hasPrefix("recebida-") && reason.range(of: "^\\d+ exercícios, \\d+ séries de trabalho\\.$", options: .regularExpression) != nil)
            let perWeek: Double
            if !isPlan || plan.id.isEmpty { perWeek = 0 }
            else if case .array(let rotation) = plan.object("rules").fields["rotation"], !rotation.isEmpty {
                perWeek = (plan.number("gym_per_week") ?? 0) / Double(rotation.count) * Double(rotation.filter { $0 == routine.fields["split_key"] }.count)
            } else { perWeek = Double(plan.array("days").filter { $0.string("kind") == "gym" && $0.string("split_key") == routine.string("split_key") }.count) }
            for row in b.array("allRoutineItems") where !row.deleted && row.string("routine_id") == routine.id {
                guard let group = riskRules.object("groups").string(row.string("exercise_id") ?? "") else { continue }
                values[group, default: 0] += (row.number("sets") ?? 0) * perWeek
            }
        }
        let easy = p.bool("returning") == true || p.string("level") == "iniciante" || p.string("goal") == "corrida" || (p.string("age_range") == "60+" && p.string("level") != "avancado")
        let ceiling: Double = easy ? 10 : p.string("level") == "intermediario" ? 16 : 20
        let focuses: [String]
        if case .array(let a) = p.fields["focus"] { focuses = a.compactMap { if case .string(let s) = $0 { return s }; return nil } }
        else { focuses = p.string("focus").map { [$0] } ?? [] }
        let focusGroups = Set(focuses.flatMap { f -> [String] in
            guard case .array(let a) = riskRules.object("focusGroups").fields[f] else { return [] }
            return a.compactMap { if case .string(let s) = $0 { return s }; return nil }
        })
        let volume = RoutineReview.groups.compactMap { g -> ReadRow? in
            guard let n = values[g] else { return nil }; return ReadRow(fields: ["group": .string(g), "sets": .number(n)])
        }
        let warnings = volume.filter { v in
            let cap = ceiling + (p.string("gender") == "feminino" ? 2 : 0) + (focusGroups.contains(v.string("group") ?? "") ? 4 : 0)
            return (v.number("sets") ?? 0) > cap
        }.map { ReadRow(fields: ["group": $0.fields["group"]!, "code": .string("acima_teto")]) }
        return ReadRow(fields: ["volume": .array(volume.map { .object($0.fields) }), "warnings": .array(warnings.map { .object($0.fields) })])
    }
    private static let riskRules: ReadRow = {
        let url = Bundle.module.url(forResource: "analysis-rules", withExtension: "json")!
        return try! JSONDecoder().decode(ReadRow.self, from: Data(contentsOf: url))
    }()
    /// weekRisks from the existing Waltér engine, with taxonomy/sources generated by TS.
    static func risks(_ a: ReadRow, binding b: ReadRow) -> [ReadRow] {
        let p = b.object("params"), plan = b.object("plan"), target = b.object("routine")
        guard !p.fields.isEmpty, let slot = a.number("slot"), slot >= 0, slot < Double(b.array("items").count), slot == floor(slot) else { return [] }
        let item = b.array("items")[Int(slot)]
        let exercise = item.string("original_exercise_id") ?? item.string("exercise_id")
        let routines = b.fields["routines"] == nil ? [target] : b.array("routines")
        let allItems = b.fields["allRoutineItems"] == nil ? b.array("routineItems") : b.array("allRoutineItems")
        func isPlan(_ r: ReadRow) -> Bool {
            if let origin = r.string("origin") { return origin == "plano" }
            if r.id.hasPrefix("pronta-") || r.id.hasPrefix("recebida-") { return false }
            let reason = r.string("reason") ?? ""
            return reason.range(of: "^\\d+ exercícios, \\d+ séries de trabalho\\.$", options: .regularExpression) != nil
        }
        func frequency(_ r: ReadRow) -> Double {
            guard !plan.id.isEmpty, isPlan(r) else { return 0 }
            if case .array(let rotation) = plan.object("rules").fields["rotation"], !rotation.isEmpty {
                let count = rotation.filter { $0 == r.fields["split_key"] }.count
                return (plan.number("gym_per_week") ?? 0) / Double(rotation.count) * Double(count)
            }
            return Double(plan.array("days").filter { $0.string("kind") == "gym" && $0.string("split_key") == r.string("split_key") }.count)
        }
        func volume(_ edited: Bool) -> (order: [String], values: [String: Double]) {
            var order: [String] = [], values: [String: Double] = [:]
            for routine in routines where !routine.deleted && routine.bool("archived") != true {
                let perWeek = frequency(routine)
                for var row in allItems where !row.deleted && row.string("routine_id") == routine.id {
                    if edited && routine.id == target.id && row.string("exercise_id") == exercise {
                        if a.string("operation") == "series" { row.fields["sets"] = a.fields["sets"] }
                        if a.string("operation") == "trocar" { row.fields["exercise_id"] = a.fields["replacement"] }
                    }
                    guard let group = riskRules.object("groups").string(row.string("exercise_id") ?? "") else { continue }
                    if values[group] == nil { order.append(group) }
                    values[group, default: 0] += (row.number("sets") ?? 0) * perWeek
                }
            }
            return (order, values)
        }
        let before = volume(false), after = volume(true)
        let older = p.string("age_range") == "60+"
        let easy = p.bool("returning") == true || p.string("level") == "iniciante" || p.string("goal") == "corrida" || (older && p.string("level") != "avancado")
        let grow: Double = easy ? 6 : p.string("level") == "intermediario" ? 10 : 12
        let ceiling: Double = easy ? 10 : p.string("level") == "intermediario" ? 16 : 20
        let focuses: [String]
        if case .array(let values) = p.fields["focus"] { focuses = values.compactMap { if case .string(let s) = $0 { return s }; return nil } }
        else { focuses = p.string("focus").map { [$0] } ?? [] }
        let focusGroups = Set(focuses.flatMap { focus -> [String] in
            guard case .array(let groups) = riskRules.object("focusGroups").fields[focus] else { return [] }
            return groups.compactMap { if case .string(let s) = $0 { return s }; return nil }
        })
        func fmt(_ n: Double) -> String { n == floor(n) ? String(Int(n)) : String(format: "%.1f", locale: Locale(identifier: "en_US_POSIX"), n).replacingOccurrences(of: ".", with: ",") }
        func label(_ group: String) -> String { riskRules.object("labels").string(group) ?? group }
        func risk(_ text: String, _ source: String) -> ReadRow { ReadRow(fields: ["text": .string(text), "source": .string(riskRules.string(source) ?? "")]) }
        var result: [ReadRow] = []
        for group in after.order {
            let n = after.values[group] ?? 0, was = before.values[group] ?? 0
            let cap = ceiling + (p.string("gender") == "feminino" ? 2 : 0) + (focusGroups.contains(group) ? 4 : 0)
            if n > cap && n > was {
                result.append(risk("\(label(group)): \(fmt(n)) séries por semana, acima de \(fmt(cap)), o teto que o app usa para o seu nível. Acima disso a recuperação costuma não acompanhar e o ganho para de crescer.", "volumeSource"))
            }
        }
        var below: [(String, Double)] = [], holding: [(String, Double)] = []
        for group in before.order {
            let was = before.values[group] ?? 0, n = after.values[group] ?? 0
            if n >= was || n >= grow { continue }
            if n < (older ? 6 : 3) { below.append((group, n)) }
            else if !older { holding.append((group, n)) }
        }
        func groupsText(_ list: [(String, Double)]) -> String {
            let names = list.enumerated().map { $0.offset == 0 ? label($0.element.0) : label($0.element.0).lowercased() }
            let joined = names.count <= 1 ? names.joined() : names.dropLast().joined(separator: ", ") + " e " + names.last!
            let lo = list.map(\.1).min()!, hi = list.map(\.1).max()!
            return "\(joined): \(lo == hi ? fmt(lo) : fmt(lo) + " a " + fmt(hi)) séries"
        }
        if !below.isEmpty {
            result.append(risk(older
                ? "\(groupsText(below)) por semana. Depois dos 60, manter o músculo pede uns 2 treinos com 2 a 3 séries por exercício; com menos, ele tende a diminuir."
                : "\(groupsText(below)) por semana, abaixo até do que costuma manter o músculo. Com tão pouco, ele pode diminuir.", "maintenanceSource"))
        }
        if !holding.isEmpty {
            result.append(risk("\(groupsText(holding)) por semana, no nível de manter, não de ganhar (para ganhar, o app usa \(fmt(grow)) ou mais). Até uns 60 anos, isso costuma bastar para não perder enquanto outro grupo é prioridade.", "maintenanceSource"))
        }
        return result
    }
}
